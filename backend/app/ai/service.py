def ai_settings(db: Session) -> dict:
    row = db.get(SystemSetting, "ai")
    return dict(row.value) if row else {}


def ai_consent_ok(db: Session, student: Student) -> bool:
    """Minors need an explicit guardian 'ai_processing' consent (DPDP Act)."""
    if not requires_guardian(student):
        return True
    latest = db.scalar(select(ConsentRecord).where(ConsentRecord.student_id == student.id,
                                                   ConsentRecord.consent_type == "ai_processing")
                       .order_by(ConsentRecord.created_at.desc()))
    return bool(latest and latest.granted)


def sanitize(text: str, limit: int = 1000) -> str:
    text = re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", " ", text or "")
    text = re.sub(r"</?\s*(facts|student_message)[^>]*>", "", text, flags=re.I)
    return text.strip()[:limit]


def build_facts(db: Session, s: Student, include_activities: bool = False) -> dict:
    domains = {d.id: d for d in db.scalars(select(Domain).where(Domain.deleted_at.is_(None))).all()}
    scores = {sc.domain_id: sc for sc in latest_scores(db, s.id)}
    chosen = {i.domain_id for i in active_interests(db, s.id) if i.subdomain_id is None}
    since = datetime.now(timezone.utc) - timedelta(days=30)
    recent = db.scalars(select(ProgressEvent).where(ProgressEvent.student_id == s.id, ProgressEvent.occurred_at >= since,
                                                    ProgressEvent.is_superseded.is_(False))
                        .order_by(ProgressEvent.occurred_at.desc()).limit(25)).all()
    feedback = db.scalars(select(MentorFeedback).where(MentorFeedback.student_id == s.id,
                                                       MentorFeedback.visible_to_student.is_(True))
                          .order_by(MentorFeedback.created_at.desc()).limit(5)).all()
    badges = db.scalars(select(StudentAchievement).where(StudentAchievement.student_id == s.id)
                        .order_by(StudentAchievement.awarded_at.desc()).limit(5)).all()
    prog = progress_summary(db, s)["overall"]
    facts = {
        "first_name": s.user.first_name,
        "age_band": s.age_group.label if s.age_group else f"{age_on(s.date_of_birth)} years",
        "goals": {"skills_to_learn": s.skills_to_learn, "aspirations": s.aspirations,
                  "learning_preferences": s.learning_preferences},
        "hobbies": s.hobbies, "self_reported_strengths": s.self_reported_strengths,
        "xp": s.xp, "current_streak_days": s.current_streak,
        "overall_progress": {k: prog[k] for k in ("evidence_count", "average_performance", "improvement_points",
                                                  "trend_label", "completion_rate")},
        "domains": [{
            "name": d.name, "chosen_as_interest": d.id in chosen,
            "skill_score": scores[d.id].skill_score if d.id in scores else None,
            "progress_score": scores[d.id].progress_score if d.id in scores else None,
            "confidence": scores[d.id].confidence_label if d.id in scores else "none",
            "evidence_count": scores[d.id].evidence_count if d.id in scores else 0,
        } for d in sorted(domains.values(), key=lambda x: x.sort_order)],
        "recent_records": [{"type": e.event_type, "domain": domains[e.domain_id].name if e.domain_id in domains else None,
                            "score_pct": e.score_pct, "title": (e.payload or {}).get("title"),
                            "date": e.occurred_at.date().isoformat()} for e in recent],
        "mentor_feedback": [f.content[:300] for f in feedback],
        "badges": [b.achievement.title for b in badges],
    }
    if include_activities:
        age = age_on(s.date_of_birth)
        acts = db.scalars(select(Activity).where(Activity.status == "published", Activity.deleted_at.is_(None),
                                                 Activity.min_age <= age, Activity.max_age >= age)
                          .order_by(Activity.difficulty).limit(40)).all()
        facts["available_activities"] = [{"id": str(a.id), "title": a.title, "domain": a.domain.name,
                                          "difficulty": a.difficulty} for a in acts]
    return facts


def report_facts(db: Session, s: Student, days: int = 7) -> ReportFacts:
    since = datetime.now(timezone.utc) - timedelta(days=days)
    events = db.scalars(select(ProgressEvent).where(ProgressEvent.student_id == s.id,
                                                    ProgressEvent.occurred_at >= since)).all()
    from ..models import XPTransaction
    xp = sum(x.amount for x in db.scalars(select(XPTransaction).where(XPTransaction.student_id == s.id,
                                                                     XPTransaction.created_at >= since)).all())
    domains = {d.id: d for d in db.scalars(select(Domain).where(Domain.deleted_at.is_(None))).all()}
    scores = {sc.domain_id: sc for sc in latest_scores(db, s.id)}
    chosen = {i.domain_id for i in active_interests(db, s.id) if i.subdomain_id is None}
    feedback = db.scalars(select(MentorFeedback).where(MentorFeedback.student_id == s.id,
                                                       MentorFeedback.visible_to_guardian.is_(True),
                                                       MentorFeedback.created_at >= since)).all()
    badges = db.scalars(select(StudentAchievement).where(StudentAchievement.student_id == s.id,
                                                         StudentAchievement.awarded_at >= since)).all()
    return ReportFacts(
        student_first_name=s.user.first_name,
        period_label=f"the last {days} days",
        activities_completed=sum(e.event_type in ("activity_submitted", "project_submitted") and e.score_pct is None
                                 for e in events),
        assessments_completed=sum(e.event_type == "assessment_completed" for e in events),
        xp_earned=xp, streak_days=s.current_streak,
        domains=[DomainFact(domain_id=str(d.id), name=d.name, selected=d.id in chosen,
                            skill_score=scores[d.id].skill_score if d.id in scores else None,
                            progress_score=scores[d.id].progress_score if d.id in scores else None,
                            confidence_label=scores[d.id].confidence_label if d.id in scores else "none",
                            evidence_count=scores[d.id].evidence_count if d.id in scores else 0)
                 for d in sorted(domains.values(), key=lambda x: x.sort_order)],
        recent_feedback=[f.content for f in feedback],
        achievements=[b.achievement.title for b in badges],
        trend_label=progress_summary(db, s)["overall"]["trend_label"],
    )


def _log(db: Session, user: User | None, feature: str, provider: str, model: str | None, status: str,
         in_tok: int = 0, out_tok: int = 0, latency: int = 0, error: str | None = None) -> None:
    db.add(AIUsageLog(user_id=user.id if user else None, feature=feature, provider=provider, model=model,
                      input_tokens=in_tok, output_tokens=out_tok, latency_ms=latency, status=status, error_code=error))
    log.info("ai_request", extra={"feature": feature, "provider": provider, "status": status,
                                  "input_tokens": in_tok, "output_tokens": out_tok, "latency_ms": latency})


def run(db: Session, user: User, student: Student, feature: str, system: str, prompt: str,
        schema: type[BaseModel], fallback) -> dict:
    """Try the LLM; on any problem fall back to the deterministic engine."""
    s = get_settings()
    ok, _ = limiter.hit(f"ai:{user.id}", s.AI_RATE_LIMIT_PER_HOUR, 3600)
    if not ok:
        _log(db, user, feature, "none", None, "rate_limited")
        db.commit()
        raise RateLimited("AI request limit reached for this hour. Please try again later.")
    settings_override = ai_settings(db)
    provider = get_provider(settings_override)
    consent = ai_consent_ok(db, student)
    if provider is not None and consent:
        try:
            res = provider.generate(system=system, prompt=prompt, schema=schema,
                                    max_tokens=int(settings_override.get("max_tokens", s.AI_MAX_OUTPUT_TOKENS)))
            _log(db, user, feature, res.provider, res.model, "ok", res.input_tokens, res.output_tokens, res.latency_ms)
            return {"source": "ai", "label": AI_LABEL, "provider": res.provider, "model": res.model,
                    "data": res.output.model_dump()}
        except AIProviderError as e:
            _log(db, user, feature, provider.name, getattr(provider, "model", None), "fallback", error=e.code)
        except Exception as e:  # never let an AI failure break the page
            log.exception("ai_unexpected_error")
            _log(db, user, feature, provider.name, getattr(provider, "model", None), "error", error=type(e).__name__)
    else:
        _log(db, user, feature, "engine", None, "fallback", error="no_consent" if provider and not consent else "not_configured")
    note = None
    if provider is not None and not consent:
        note = "AI features are paused until a guardian gives AI-processing consent. Showing rule-based guidance instead."
    return {"source": "engine", "label": ENGINE_LABEL, "provider": "engine", "model": None, "data": fallback(),
            "note": note}


