def summarize(db: Session, user: User, s: Student) -> dict:
    facts = build_facts(db, s)
    rf = report_facts(db, s, 30)

    def fb():
        summ = build_progress_summary(rf)
        strong = [d for d in facts["domains"] if d["skill_score"] is not None]
        return {"headline": summ["headline"], "highlights": summ["paragraphs"][1:4],
                "growth_areas": [f"Keep building evidence in {d['name']}" for d in facts["domains"]
                                 if d["chosen_as_interest"] and d["confidence"] in ("none", "low")][:3],
                "next_steps": ["Complete one activity in a chosen interest this week",
                               "Write a short reflection after your next activity"] +
                              (["Try a harder challenge in " + max(strong, key=lambda d: d["skill_score"])["name"]] if strong else [])}
    return run(db, user, s, "summary", P.SYSTEM_BASE, P.summary_prompt(facts), P.SummaryOutput, fb)


def chat(db: Session, user: User, s: Student, message: str) -> dict:
    msg = sanitize(message)
    facts = build_facts(db, s, include_activities=True)
    valid_ids = {a["id"] for a in facts["available_activities"]}

    def fb():
        chosen = [d["name"] for d in facts["domains"] if d["chosen_as_interest"]]
        picks = [a for a in facts["available_activities"] if a["domain"] in chosen][:3] or facts["available_activities"][:3]
        return {"reply": ("I'm the rule-based helper right now, so I can't answer open questions in detail. "
                          f"Based on your interests ({', '.join(chosen) or 'none chosen yet'}), here are some activities "
                          "you could try next. Your mentor is also a great person to ask!"),
                "suggested_activity_ids": [a["id"] for a in picks]}
    out = run(db, user, s, "chat", P.SYSTEM_BASE, P.chat_prompt(facts, msg), P.ChatOutput, fb)
    # Output validation: suggestions must reference real, eligible activities.
    out["data"]["suggested_activity_ids"] = [i for i in out["data"].get("suggested_activity_ids", []) if i in valid_ids][:5]
    titles = {a["id"]: a for a in facts["available_activities"]}
    out["data"]["suggested_activities"] = [titles[i] for i in out["data"]["suggested_activity_ids"]]
    return out


def project_ideas(db: Session, user: User, s: Student, domain_id: uuid.UUID) -> dict:
    d = db.get(Domain, domain_id)
    if d is None:
        raise NotFound("Domain not found")
    facts = build_facts(db, s)
    junior = age_on(s.date_of_birth) <= 11

    def fb():
        subs = [x.name for x in d.subdomains][:3] or [d.name]
        return {"ideas": [{
            "title": f"{sub} mini-project", "description": f"Create something small that shows what you know about {sub}.",
            "steps": ["Pick a question or problem you care about", "Sketch a plan", "Build or try it",
                      "Share it and reflect on what you learned"],
            "skills_practised": [sub, "planning", "reflection"], "estimated_hours": 2 if junior else 5} for sub in subs]}
    return run(db, user, s, "project_ideas", P.SYSTEM_BASE, P.project_ideas_prompt(facts, d.name),
               P.ProjectIdeasOutput, fb)


def parent_report(db: Session, user: User, s: Student, days: int = 30) -> dict:
    facts = build_facts(db, s)
    rf = report_facts(db, s, days)

    def fb():
        rep = build_parent_report(rf)
        return {"title": rep["title"], "sections": [
            {"title": sec["title"], "body": sec.get("body") or "; ".join(
                (f"{i['domain']}: skill {i['skill_score'] if i['skill_score'] is not None else 'not yet measured'}, "
                 f"{i['confidence']} confidence") if isinstance(i, dict) else str(i) for i in sec.get("items", []))}
            for sec in rep["sections"]]}
    return run(db, user, s, "parent_report", P.SYSTEM_BASE, P.parent_report_prompt(facts), P.ParentReportOutput, fb)


def mentor_insights(db: Session, user: User, s: Student) -> dict:
    facts = build_facts(db, s)

    def fb():
        assessed = [d for d in facts["domains"] if d["evidence_count"]]
        return {
            "observations": [f"{d['name']}: {d['evidence_count']} records, skill "
                             f"{d['skill_score'] if d['skill_score'] is not None else 'n/a'}, confidence {d['confidence']}"
                             for d in assessed] or ["No scored evidence yet."],
            "suggested_focus": [d["name"] for d in facts["domains"] if d["chosen_as_interest"] and d["confidence"] in ("none", "low")][:3],
            "questions_to_ask": ["Which recent activity did you enjoy most, and why?",
                                 "Is there a domain you are curious about but have not tried?"],
            "data_gaps": [d["name"] for d in facts["domains"] if d["evidence_count"] < 3],
        }
    return run(db, user, s, "mentor_insights", P.SYSTEM_BASE, P.mentor_insights_prompt(facts), P.MentorInsightsOutput, fb)


def interest_analysis(db: Session, user: User, s: Student) -> dict:
    facts = build_facts(db, s)

    def fb():
        chosen = [d for d in facts["domains"] if d["chosen_as_interest"]]
        return {
            "summary": f"You chose {len(chosen)} domain(s). Your choices are what matter most - evidence just helps you plan.",
            "aligned_interests": [d["name"] for d in chosen if d["confidence"] in ("moderate", "high")],
            "keep_exploring": [d["name"] for d in chosen if d["confidence"] in ("none", "low")],
            "worth_trying": [d["name"] for d in facts["domains"] if not d["chosen_as_interest"] and d["evidence_count"] == 0],
        }
    return run(db, user, s, "interest_analysis", P.SYSTEM_BASE, P.interest_analysis_prompt(facts),
               P.InterestAnalysisOutput, fb)


def skill_suggestions(db: Session, user: User, s: Student) -> dict:
    facts = build_facts(db, s)

    def fb():
        goals = s.skills_to_learn or ["a skill in one of your chosen domains"]
        return {"suggestions": [f"Spend 20 minutes twice a week practising {g}." for g in goals[:3]] +
                ["After each activity, note one thing you would do differently next time."]}
    return run(db, user, s, "skill_suggestions", P.SYSTEM_BASE, P.skill_suggestions_prompt(facts),
               P.SkillSuggestionsOutput, fb)


def ensure_ai_access(user: User, s: Student) -> None:
    if user.role == "guardian":
        raise Forbidden("Guardians can request parent reports only")


